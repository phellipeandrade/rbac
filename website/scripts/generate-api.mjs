import {execFileSync} from 'node:child_process';
import {cpSync, mkdirSync, readdirSync, rmSync, writeFileSync} from 'node:fs';
import {fileURLToPath, pathToFileURL} from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = path.join(root, 'docs/api/reference');
const localized = path.join(root, 'i18n/pt-BR/docusaurus-plugin-content-docs/current/api/reference');

execFileSync(process.execPath, [
  '--import', pathToFileURL(path.join(root, 'scripts/typedoc-minimatch-compat.mjs')).href,
  path.join(root, 'node_modules/typedoc/bin/typedoc'),
  '--options', path.join(root, 'typedoc.json')
], {cwd: root, stdio: 'inherit'});

// Docusaurus derives translation keys from autogenerated category labels.
// TypeDoc repeats labels such as "functions" under multiple entry points,
// so each generated directory needs a stable, globally unique category key.
function writeCategoryKeys(directory) {
  for (const entry of readdirSync(directory, {withFileTypes: true})) {
    if (!entry.isDirectory()) continue;
    const child = path.join(directory, entry.name);
    const categoryPath = path.relative(source, child).split(path.sep).join('/');
    writeFileSync(path.join(child, '_category_.json'), `${JSON.stringify({
      label: entry.name,
      key: `api-reference-${categoryPath.replace(/[^a-zA-Z0-9/-]/g, '-').replaceAll('/', '-')}`
    }, null, 2)}\n`);
    writeCategoryKeys(child);
  }
}

writeCategoryKeys(source);
rmSync(localized, {recursive: true, force: true});
mkdirSync(path.dirname(localized), {recursive: true});
// Identifiers and signatures remain identical in each language. Generated
// comments fall back to the source language until translations are authored.
cpSync(source, localized, {recursive: true});
