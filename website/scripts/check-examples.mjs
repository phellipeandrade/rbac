import {mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
import ts from 'typescript';

const website = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const repository = path.dirname(website);
const guides = [
  {label: 'en', directory: path.join(website, 'docs')},
  {label: 'pt-BR', directory: path.join(website, 'i18n/pt-BR/docusaurus-plugin-content-docs/current')}
];
const scratch = mkdtempSync(path.join(repository, '.rbac-doc-examples-'));
const entrypoints = {
  '@rbac/rbac': ['src/index.ts'],
  '@rbac/rbac/adapters': ['src/adapters/index.ts'],
  '@rbac/rbac/middlewares': ['src/middlewares/index.ts'],
  '@rbac/rbac/helpers': ['src/helpers.ts'],
  '@rbac/rbac/schemas': ['src/roles.schema.ts'],
  '@rbac/rbac/roles.schema': ['src/roles.schema.ts']
};

try {
  const files = [];
  let checkedJavaScript = 0;
  let checkedJSON = 0;
  const sources = [{label: 'README', filename: path.join(repository, 'README.md')}];
  for (const {label, directory} of guides) {
    // API reference pages are generated by TypeDoc and checked when TypeDoc runs.
    for (const guide of readdirSync(directory).filter(name => /\.mdx?$/.test(name))) {
      sources.push({label: `${label}-${guide}`, filename: path.join(directory, guide)});
    }
  }

  for (const {label, filename} of sources) {
    const markdown = readFileSync(filename, 'utf8');
    const fences = /^```(ts|typescript|tsx|js|javascript|json)(?:[^\r\n]*)\r?\n([\s\S]*?)^```/gm;
    let match;
    let index = 0;
    while ((match = fences.exec(markdown)) !== null) {
      const language = match[1];
      const example = match[2];
      const name = `${label.replace(/\W/g, '-')}-${++index}`;
      if (language === 'json') {
        try { JSON.parse(example); } catch (error) { throw new Error(`${label} JSON block ${index}: ${error.message}`, {cause: error}); }
        checkedJSON++;
        continue;
      }
      if (language === 'js' || language === 'javascript') {
        // Documentation JavaScript examples are CommonJS scripts.
        new vm.Script(example, {filename: `${label}:${index}`});
        checkedJavaScript++;
        continue;
      }
      const examplePath = path.join(scratch, `${name}.${language === 'tsx' ? 'tsx' : 'ts'}`);
      // Every example must stand alone, including those using top-level await.
      writeFileSync(examplePath, `${example}\nexport {};\n`);
      files.push(examplePath);
    }
  }

  if (!files.length) throw new Error('No TypeScript code examples found in the guides.');

  const compiler = ts.createProgram(files, {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    strict: true,
    jsx: ts.JsxEmit.ReactJSX,
    noEmit: true,
    skipLibCheck: false,
    esModuleInterop: true,
    baseUrl: repository,
    paths: entrypoints,
    types: ['node']
  });
  const errors = ts.getPreEmitDiagnostics(compiler);
  if (errors.length) {
    console.error(ts.formatDiagnosticsWithColorAndContext(errors, {
      getCanonicalFileName: file => file,
      getCurrentDirectory: () => repository,
      getNewLine: () => '\n'
    }));
    process.exitCode = 1;
  } else {
    console.log(`Validated ${files.length} independent TypeScript examples, ${checkedJavaScript} JavaScript syntax examples and ${checkedJSON} JSON examples across README, English and pt-BR guides.`);
  }
} finally {
  rmSync(scratch, {recursive: true, force: true});
}
